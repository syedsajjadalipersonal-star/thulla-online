// Builds the Nakama runtime module: packages/nakama/build/index.js, one ES5 file.
//
// tsc compiles the match handler and the engine to ES5 CommonJS. This script then joins those
// files behind a small require() and adds the global functions Nakama looks for: Nakama finds
// InitModule and every registered handler by its global function name, so they cannot live
// inside a module. The result is parsed as ES5 before it is written.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'acorn';

const root = fileURLToPath(new URL('..', import.meta.url));
const cjs = join(root, 'build/nakama-cjs');
const out = join(root, 'packages/nakama/build/index.js');

rmSync(cjs, { recursive: true, force: true });
execFileSync(process.execPath, [join(root, 'node_modules/typescript/bin/tsc'), '-p', join(root, 'packages/nakama/tsconfig.json')], {
  stdio: 'inherit',
});

function files(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? files(path) : path.endsWith('.js') ? [path] : [];
  });
}

const modules = files(cjs)
  .map((path) => {
    const id = relative(cjs, path).replace(/\\/g, '/').replace(/\.js$/, '');
    return `${JSON.stringify(id)}: function (require, module, exports) {\n${readFileSync(path, 'utf8')}\n}`;
  })
  .join(',\n');

// Handlers Nakama calls, each forwarded to the export of the same name in nakama/src/match.
const handlers = ['matchInit', 'matchJoinAttempt', 'matchJoin', 'matchLeave', 'matchLoop', 'matchTerminate', 'matchSignal'];
const rpcs = { create_table: 'rpcCreateTable', join_by_code: 'rpcJoinByCode' };
const forward = (name) => `function ${name}() {\n  return Thulla.${name}.apply(null, arguments);\n}`;

const bundle = `// Thulla match handler for Nakama. Generated by scripts/build-nakama.mjs; do not edit.
var __modules = {
${modules}
};
var __cache = {};
function __require(from, request) {
  var parts = request.charAt(0) === '.' ? from.split('/').slice(0, -1).concat(request.split('/')) : request.split('/');
  var path = [];
  for (var i = 0; i < parts.length; i++) {
    if (parts[i] === '..') path.pop();
    else if (parts[i] !== '.' && parts[i] !== '') path.push(parts[i]);
  }
  var id = path.join('/');
  if (!__modules[id] && __modules[id + '/index']) id = id + '/index';
  if (!__modules[id]) throw new Error('Module not found: ' + request + ' from ' + from);
  if (!__cache[id]) {
    var module = { exports: {} };
    __cache[id] = module;
    __modules[id](function (r) { return __require(id, r); }, module, module.exports);
  }
  return __cache[id].exports;
}
var Thulla = __require('', 'nakama/src/match');

${handlers.map(forward).join('\n')}
${Object.values(rpcs).map(forward).join('\n')}

function InitModule(ctx, logger, nk, initializer) {
${Object.entries(rpcs)
  .map(([id, fn]) => `  initializer.registerRpc('${id}', ${fn});`)
  .join('\n')}
  initializer.registerMatch('thulla', {
${handlers.map((h) => `    ${h}: ${h}`).join(',\n')}
  });
  logger.info('Thulla module loaded');
}
`;

parse(bundle, { ecmaVersion: 5, sourceType: 'script' });
mkdirSync(join(root, 'packages/nakama/build'), { recursive: true });
writeFileSync(out, bundle);
console.log(`Built packages/nakama/build/index.js (${(bundle.length / 1024).toFixed(0)} KB), parsed as ES5`);
